router.post('/operations/assignments',authenticate,requireRole('COMPANY'),async(req,res)=>{
 try{
 const cid=req.user.companyId||req.user.id, routeId=String(req.body.routeId||''),driverId=String(req.body.driverId||''),vehicleId=String(req.body.vehicleId||'');
 if(!routeId||!driverId||!vehicleId)return res.status(400).json({success:false,error:'Route, driver and company vehicle are required.'});
 const r=await DB.prepare('SELECT id FROM routes WHERE id=? AND active=TRUE').get(routeId);
 const d=await DB.prepare("SELECT id FROM users WHERE id=? AND role='DRIVER' AND companyId=? AND status='ACTIVE'").get(driverId,cid);
 const v=await DB.prepare('SELECT id FROM vehicles WHERE id=? AND companyId=?').get(vehicleId,cid);
 if(!r||!d||!v)return res.status(403).json({success:false,error:'Route, driver and vehicle must be valid and belong to this company.'});
 const conflict=await DB.prepare("SELECT id FROM company_route_assignments WHERE status='ACTIVE' AND (driver_id=? OR vehicle_id=?)").get(driverId,vehicleId);
 if(conflict)return res.status(409).json({success:false,error:'Driver or vehicle already has an active assignment.'});
 const id='cassign_'+crypto.randomUUID().replace(/-/g,'').slice(0,16);
 await DB.prepare("INSERT INTO company_route_assignments(id,company_id,route_id,driver_id,vehicle_id,status) VALUES(?,?,?,?,?,'ACTIVE')").run(id,cid,routeId,driverId,vehicleId);
 await DB.prepare('UPDATE vehicles SET driverId=?,assignedRouteId=? WHERE id=? AND companyId=?').run(driverId,routeId,vehicleId,cid);
 res.status(201).json({success:true,assignment:{id,companyId:cid,routeId,driverId,vehicleId,status:'ACTIVE'}});
 }catch(e){console.error('[Company] assignment:',e);res.status(500).json({success:false,error:'Could not assign route.'});}
});
