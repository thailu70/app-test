const express = require('express');
const crypto = require('crypto');
const bcrypt = require('bcryptjs');
const { DB } = require('../db');
const { authenticate, requireRole, signToken } = require('../middleware/auth');
const router = express.Router();

// Public directory is used by Intercity driver registration; Daily Commute does not require a company.
router.get('/', async (_req, res) => {
  try {
    const companies = await DB.prepare("SELECT id, name FROM transport_companies WHERE status = 'ACTIVE' ORDER BY name ASC").all();
    res.setHeader('Cache-Control', 'no-store');
    res.json({ success: true, companies });
  } catch (err) { console.error('[Companies] list failed:', err); res.status(503).json({ success: false, error: 'Company list unavailable.' }); }
});

// Company registration code is generated by an authenticated administrator and is single-use.
router.post('/register', async (req, res) => {
  try {
    const name = String(req.body.companyName || '').trim(), fullName = String(req.body.fullName || '').trim();
    const phone = String(req.body.phone || '').trim(), code = String(req.body.secretCode || '').trim(), password = req.body.password;
    if (name.length < 2 || fullName.length < 2 || !phone || !code || typeof password !== 'string' || password.length < 10)
      return res.status(400).json({ success: false, error: 'Company, representative, phone, code and password (10+ characters) are required.' });
    const c = await DB.prepare("SELECT * FROM transport_companies WHERE LOWER(name)=LOWER(?) AND status='INVITED'").get(name);
    if (!c || !c.registration_secret_hash || !(await bcrypt.compare(code, c.registration_secret_hash)))
      return res.status(403).json({ success: false, error: 'Invalid or already-used company registration code.' });
    const phoneUsed = await DB.prepare('SELECT id FROM transport_companies WHERE phone = ?').get(phone);
    if (phoneUsed) return res.status(409).json({ success: false, error: 'Phone already registered for a company.' });
    const hash = await bcrypt.hash(password, 12);
    await DB.prepare("UPDATE transport_companies SET phone=?, representative_name=?, password_hash=?, registration_secret_hash=NULL, status='ACTIVE', updated_at=CURRENT_TIMESTAMP WHERE id=? AND status='INVITED' AND registration_secret_hash=?")
      .run(phone, fullName, hash, c.id, c.registration_secret_hash);
    const token = signToken({ id:c.id, role:'COMPANY', companyId:c.id, companyName:c.name, fullName, phone });
    res.status(201).json({ success:true, token, user:{ id:c.id, role:'COMPANY', companyId:c.id, companyName:c.name, fullName, phone } });
  } catch (e) { console.error('[Company] register failed:', e); res.status(500).json({ success:false, error:'Company registration failed.' }); }
});

router.post('/login', async (req,res) => {
  try {
    const phone=String(req.body.phone||'').trim(), password=req.body.password;
    const c=await DB.prepare("SELECT * FROM transport_companies WHERE phone=? AND status='ACTIVE'").get(phone);
    if (!c || !c.password_hash || !(await bcrypt.compare(String(password||''),c.password_hash))) return res.status(401).json({success:false,error:'Invalid company credentials.'});
    const fullName=c.representative_name||c.name;
    res.json({success:true,token:signToken({id:c.id,role:'COMPANY',companyId:c.id,companyName:c.name,fullName,phone}),user:{id:c.id,role:'COMPANY',companyId:c.id,companyName:c.name,fullName,phone}});
  } catch(e) { console.error('[Company] login failed:',e); res.status(500).json({success:false,error:'Company login failed.'}); }
});
router.get('/me', authenticate, requireRole('COMPANY'), async(req,res)=>{
  const c=await DB.prepare("SELECT id,name,phone,representative_name,status FROM transport_companies WHERE id=? AND status='ACTIVE'").get(req.user.companyId||req.user.id);
  if(!c)return res.status(404).json({success:false,error:'Company not found.'}); res.json({success:true,company:c});
});
