'use strict';
// Only the disposable CI PostgreSQL service may run this integration check.
const assert = require('node:assert/strict');
const bcrypt = require('bcryptjs');
if (process.env.NODE_ENV !== 'test' || !process.env.DATABASE_URL) throw new Error('A disposable test PostgreSQL database is required.');
const { DB } = require('../src/db');
const { runDatabaseMigrations } = require('../src/server');
const { createAccountRecoveryService } = require('../src/services/account-recovery');
const { getSessionVersion, loadCredentialSnapshot, sessionIsCurrent } = require('../src/services/account-sessions');
const { createApplicationNotificationService } = require('../src/services/application-notifications');
(async () => {
  await runDatabaseMigrations();
  const hash = await bcrypt.hash('PostgreSQL recovery fixture', 4);
  await DB.prepare("INSERT INTO users(id,role,fullName,phone,passwordHash,status) VALUES('ci_recovery_passenger','PASSENGER','CI Recovery Passenger','+251912000091',?,'ACTIVE'),('ci_recovery_driver','DRIVER','CI Recovery Driver','+251912000092',?,'PENDING')").run(hash, hash);
  const messages = [];
  const recovery = createAccountRecoveryService({ sendSms: async (phone, message) => { messages.push({ phone, message }); return { sent: true }; } });
  await recovery.request({ role: 'PASSENGER', phone: '0912000091' }); await recovery.waitForDeliveries();
  const code = /\b(\d{6})\b/.exec(messages[0].message)[1];
  const attempts = await Promise.allSettled([1, 2].map(() => recovery.reset({ role: 'PASSENGER', phone: '0912000091', code, newPassword: 'Recovered PostgreSQL password' })));
  assert.equal(attempts.filter(item => item.status === 'fulfilled').length, 1, 'Concurrent resets consume one delivered challenge only once');
  assert.equal(await getSessionVersion('ci_recovery_passenger', 'PASSENGER'), 1);
  assert.equal(await sessionIsCurrent({ id: 'ci_recovery_passenger', role: 'PASSENGER' }), false);
  assert.equal(await sessionIsCurrent({ id: 'ci_recovery_passenger', role: 'PASSENGER', sessionVersion: 1 }), true);
  const account = await DB.prepare("SELECT * FROM users WHERE id='ci_recovery_passenger'").get();
  assert.equal(account.status, 'ACTIVE'); assert.equal(await bcrypt.compare('Recovered PostgreSQL password', account.passwordHash), true);
  const credentials = await loadCredentialSnapshot(account.id, 'PASSENGER');
  assert.equal(credentials.passwordHash, account.passwordHash); assert.equal(Number(credentials.credential_session_version), 1);
  let clock = Date.now(), providerAvailable = false;
  const notifications = createApplicationNotificationService({ now: () => clock, sendSms: async () => ({ sent: providerAvailable }) });
  await assert.rejects(() => DB.transaction(async tx => { await notifications.queue(tx, { accountId: 'ci_recovery_driver', role: 'DRIVER', decision: 'ACCEPT', eventKey: 'ci_recovery_rollback' }); throw Error('rollback'); }), /rollback/);
  assert.equal(Boolean(await DB.prepare("SELECT id FROM application_notification_outbox WHERE event_key='ci_recovery_rollback'").get()), false);
  await DB.transaction(tx => notifications.queue(tx, { accountId: 'ci_recovery_driver', role: 'DRIVER', decision: 'CORRECTIONS', eventKey: 'ci_recovery_correction' }));
  assert.ok((await notifications.flush()).failed >= 1);
  assert.equal((await DB.prepare("SELECT status FROM users WHERE id='ci_recovery_driver'").get()).status, 'PENDING');
  clock += 60001; providerAvailable = true;
  assert.ok((await notifications.flush()).sent >= 1);
  assert.equal((await DB.prepare("SELECT status FROM application_notification_outbox WHERE event_key='ci_recovery_correction'").get()).status, 'SENT');
  console.log('PostgreSQL recovery/outbox passed: delivered ownership proof, single-use row locks, session revocation, rollback-safe queue and provider retries.');
  process.exit(0);
})().catch(error => { console.error(error); process.exit(1); });
