'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
process.env.NODE_ENV = 'test';
process.env.JWT_SECRET = 'ride-notification-fixture-secret-not-production';
process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'passo-ride-push-'));
if (process.env.MOBILITY_TEST_POSTGRES === 'true') {
  if (process.env.CI !== 'true' || !process.env.DATABASE_URL) throw Error('Disposable CI PostgreSQL required.');
} else delete process.env.DATABASE_URL;
const { DB } = require('../src/db');
const { initRidesSchema } = require('../src/services/rides-schema');
const { createMobilityPushService } = require('../src/services/mobility-push');
test('taxi and shared notifications use encrypted account bindings, deduplication and live authorization', async () => {
  await initRidesSchema(DB);
  const driver = { id: 'push-ride-driver', role: 'DRIVER' }, rider = { id: 'push-ride-rider', role: 'PASSENGER' }, another = { id: 'push-ride-other', role: 'PASSENGER' };
  for (const user of [driver, rider, another]) await DB.prepare("INSERT INTO users(id,role,fullName,phone,passwordHash,status) VALUES(?,?,?,?,?,'ACTIVE')").run(user.id, user.role, 'Private fixture name', user.id, 'unused');
  const clock = Date.now(), at = new Date(clock).toISOString();
  await DB.prepare('INSERT INTO ride_availability(driver_id,online,latitude,longitude,recorded_at,updated_at) VALUES(?,1,9,38.75,?,?)').run(driver.id, at, at);
  let ride = { id: 'ride_fixture', status: 'REQUESTED', passengerPhone: 'PRIVATE_PHONE', boardingPin: 'PRIVATE_PIN' };
  const dashboard = { eligible: true, online: true, calls: [ride], ride: null, sharedTrips: [], sharedRequests: [] };
  const own = { ride, rides: [ride], sharedTrips: [], bookings: [] };
  let snapshotHook = async () => {};
  const rides = { dashboard: async () => dashboard, me: async () => { await snapshotHook(); return own; }, catalog: async () => ({ settings: { notificationRadiusKm: 10 } }) };
  const deliveries = [];
  const fakeMobility = { init: async () => {}, marketplace: { opportunities: async () => ({ busy: true, requests: [] }) } };
  const push = createMobilityPushService({ db: DB, now: () => clock, service: fakeMobility, ridesService: rides,
    env: { JWT_SECRET: process.env.JWT_SECRET }, provider: { send: async (token, _copy, data) => { deliveries.push({ token, data }); return { sent: true }; } } });
  const driverToken = 'fixture-driver-ride-device-token-0123456789', riderToken = 'fixture-passenger-ride-device-token-0123456789';
  await push.registerRideAccount(driver, { token: driverToken });
  await push.registerRideAccount(rider, { token: riderToken });
  assert.equal(JSON.stringify(await DB.prepare('SELECT * FROM mobility_push_tokens').all()).includes(driverToken), false);
  await push.flush();
  assert.equal(deliveries.length, 1); assert.equal(deliveries[0].data.kind, 'TAXI'); assert.equal(deliveries[0].data.scope, 'DRIVER');
  await push.flush(); assert.equal(deliveries.length, 1, 'Repeated polling never resends a call');
  ride = { ...ride, status: 'ACCEPTED' }; dashboard.calls = []; dashboard.ride = ride; own.ride = ride; own.rides = [ride];
  await push.flush(); assert.equal(deliveries.at(-1).token, riderToken); assert.equal(deliveries.at(-1).data.eventType, 'STATUS_ACCEPTED');
  dashboard.calls = [{ id: 'must_not_notify', status: 'REQUESTED' }];
  ride = { ...ride, status: 'AT_PICKUP' }; dashboard.ride = ride; own.ride = ride; own.rides = [ride];
  await push.flush(); assert.equal(deliveries.some(value => value.data.requestId === 'must_not_notify'), false, 'An on-job driver gets no new calls');
  assert.equal(deliveries.filter(value => value.data.eventType === 'STATUS_AT_PICKUP').length, 2);
  for (const delivery of deliveries) assert.deepEqual(Object.keys(delivery.data).sort(), ['eventType', 'kind', 'requestId', 'scope']);
  assert.doesNotMatch(JSON.stringify(deliveries), /PRIVATE_|Private fixture|boardingPin|passengerPhone/);
  dashboard.sharedTrips = [{ id: 'shared_fixture', status: 'OPEN', bookings: [] }]; await push.flush();
  dashboard.sharedTrips[0].bookings = [{ id: 'booking_fixture', status: 'CONFIRMED', passengerPhone: 'PRIVATE_PHONE' }]; await push.flush();
  assert.ok(deliveries.some(value => value.data.kind === 'SHARED' && value.data.eventType === 'BOOKING_UPDATED'));
  await push.registerRideAccount(another, { token: riderToken });
  const bindings = await DB.prepare("SELECT owner_id FROM mobility_push_tokens WHERE scope='RIDE_PASSENGER'").all();
  assert.deepEqual(bindings.map(row => row.owner_id), [another.id], 'A device token cannot keep another account binding');
  await push.unregisterRideAccount(driver, { token: driverToken });
  const count = deliveries.length; dashboard.calls = [{ id: 'after_logout', status: 'REQUESTED' }]; dashboard.ride = null;
  await push.flush(); assert.equal(deliveries.some(value => value.data.requestId === 'after_logout'), false);
  await DB.prepare("UPDATE users SET status='INACTIVE' WHERE id=?").run(another.id);
  await assert.rejects(push.registerRideAccount(another, { token: riderToken }), error => error.status === 403);
  await push.flush(); assert.equal(deliveries.length, count);
  await DB.prepare("UPDATE users SET status='ACTIVE' WHERE id=?").run(another.id);
  snapshotHook = async () => { await DB.prepare("UPDATE users SET status='INACTIVE' WHERE id=?").run(another.id); };
  await assert.rejects(push.registerRideAccount(another, { token: riderToken }), error => error.status === 403, 'An account closed after the initial check cannot recreate a notification token');
  await DB.prepare("UPDATE users SET status='ACTIVE' WHERE id=?").run(another.id);
  await require('../src/services/account-deletion').initAccountDeletionSchema(DB);
  snapshotHook = async () => { await DB.prepare("INSERT INTO account_deletion_requests(id,account_id,role,status,requested_at,completed_at) VALUES('fixture-closure',?,'PASSENGER','COMPLETED',?,?)").run(another.id, at, at); };
  await assert.rejects(push.registerRideAccount(another, { token: riderToken }), error => error.status === 403, 'The permanent closure receipt also revokes registration while ACTIVE is stale');
});
